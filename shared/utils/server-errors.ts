/** Messages that carry a value, e.g. an amount; groups become the named params. */
export const SERVER_ERROR_PATTERNS: { key: string, match: RegExp, params: string[] }[] = [
  { key: "typeInUse", match: /^(\d+) products use this type; move or delete them first$/, params: ["n"] },
  { key: "imageTypes", match: /^Allowed: (.+)$/, params: ["list"] },
  { key: "minPayout", match: /^The smallest payout is (\d+)$/, params: ["amount"] },
  { key: "zarinpalRefused", match: /^ZarinPal refused the payment \((.+)\)$/, params: ["code"] },
  { key: "bundlePrice", match: /^The bundle price must be lower than the products together \((\d+)\)$/, params: ["amount"] },
  { key: "fileTypes", match: /^This product type expects (.+) files$/, params: ["list"] },
  { key: "requiredFields", match: /^Required fields missing: (.+)$/, params: ["list"] },
]

/** The i18n key and params for a server message, or null when it isn't one we know. */
export function serverErrorKey(message: string): { key: string, params: Record<string, string> } | null {
  const exact = SERVER_ERRORS[message]
  if (exact) return { key: exact, params: {} }
  for (const p of SERVER_ERROR_PATTERNS) {
    const m = message.match(p.match)
    if (m) return { key: p.key, params: Object.fromEntries(p.params.map((name, i) => [name, m[i + 1]!])) }
  }
  return null
}
